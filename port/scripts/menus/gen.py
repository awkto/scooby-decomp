#!/usr/bin/env python3
"""Generate the menu tour scripts (tour1..3.txt) used by port/tools/dt-menus (GitLab #21).

The harness script language is in port/src/script.h.  Each tour starts at power-on, so the states
captured from them are independent of one another.  Run:  python3 port/scripts/menus/gen.py

The three tours are ONE session: tour 1 starts at power-on and ends at the main menu, tour 2 continues from
there and ends with QUIT MYSTERY (soft reset), tour 3 starts with the boot after that reset.  Play them in
that order (port/scripts/menus/tour.sh 1 2 3).
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "..", "tools", "py"))
import password as pwmod

out = []


def emit(s):
    out.append(s)


def press(btns, n=6, gap=14):
    emit(f"press {btns} {n}")
    emit(f"run {gap}")


def run(n):
    emit(f"run {n}")


def shot(name):
    emit(f"shot {name}")


def boot_to_title_menu(wait_bats=False):
    """power-on -> logos (skipped with Start) -> title bats -> main menu (3 items)"""
    run(1500)
    emit("press S 4"); run(150)
    emit("press S 4"); run(150)
    if wait_bats:
        run(400)         # let the whole bat animation run out by itself
    else:
        emit("press S 4"); run(150)


class Pw:
    """cursor of the ENTER PASSWORD key grid: 5 rows x 8 columns (row 4 = icons)"""
    def __init__(self):
        self.r = self.c = 0

    def goto(self, r, c, hold=6, gap=10):
        while self.r != r:
            if (r - self.r) % 5 <= 2:
                press("D", hold, gap); self.r = (self.r + 1) % 5
            else:
                press("U", hold, gap); self.r = (self.r - 1) % 5
        while self.c != c:
            if (c - self.c) % 8 <= 4:
                press("R", hold, gap); self.c = (self.c + 1) % 8
            else:
                press("L", hold, gap); self.c = (self.c - 1) % 8

    def key(self, hold=6, gap=10, btn="A"):
        press(btn, hold, gap)

    def type_chars(self, text):
        for ch in text:
            i = pwmod.ALPHA.index(ch)
            self.goto(i // 8, i % 8)
            self.key()

    def icon(self, col):
        self.goto(4, col)
        self.key()


def title_menu_item(n):
    """cursor from item 0 to item n, then Start"""
    for _ in range(n):
        press("D", 6, 20)
    emit("press S 6"); run(160)


def to_password_screen():
    """main menu (cursor on item 0) -> PLAY BLAKE'S HOTEL -> CONTINUE -> ENTER PASSWORD"""
    title_menu_item(0)
    press("D", 6, 20)
    emit("press S 6"); run(260)


def cheat():
    for b in "ABACABLRABL":
        press(b, 9, 10)
    run(20)


def skip_intro():
    """game start: the logos/intro cutscenes need several Start presses (docs/passwords.md)"""
    for _ in range(9):
        emit("press S 4"); run(150)
    run(200)


def write(name, header):
    path = os.path.join(os.path.dirname(__file__), name)
    with open(path, "w") as f:
        f.write(header + "\n" + "\n".join(out) + "\n")
    out.clear()


# --------------------------------------------------------------------------------------- tour 1
# title screen, cheat code, sound test, password screen: typing, icons, bad END, CLEAR, cancel
boot_to_title_menu()
shot("t1_menu")
for b in "DDU":
    press(b)
cheat()
press("D")                                  # cursor to SOUND TEST (item 2)
emit("press S 6"); run(200)
shot("t1_sound0")
for b in "RRDBRRRA":
    press(b, 6, 20)
run(30)
for b in "ULLLLLLLLUUUUUUUDDDDD":
    press(b, 6, 12)
for b in "BUDRL":
    press(b, 6, 40)
shot("t1_sound1")
emit("press C 6"); run(200)                 # back to the main menu
to_password_screen()
shot("t1_pw0")
pw = Pw()
pw.type_chars("SCOOBYDOOWHEREAREYOUNOWSHAGGY")     # 29 chars: runs over into row 2
shot("t1_pw1")
for rep in range(3):
    pw.icon(5)                              # END: wrong checksum -> error sound, stays
    pw.icon(0); pw.icon(1); pw.icon(2); pw.icon(3)    # cursor left, right, switch row (twice)
    pw.icon(1); pw.icon(1); pw.icon(0); pw.icon(0)
    pw.icon(6)                              # no-op icon
    pw.icon(4)                              # CLEAR: the current game's password again
    pw.type_chars("A?!" if rep == 0 else "ZB#%")
pw.icon(7)                                  # cancel -> main menu
run(300)
shot("t1_end")
write("tour1.txt", "# Menu tour 1 (generated by gen.py): title, cheat code, sound test, password screen, cancel")

# --------------------------------------------------------------------------------------- tour 2
# (continues tour 1: the main menu) start Blake's hotel from a typed password (valid), pause menu, QUIT MYSTERY,
# soft reset
shot("t2_menu")
to_password_screen()
pw = Pw()
pw.type_chars(pwmod.encode(2))
shot("t2_pw")
pw.icon(5)                                  # END: valid -> sound, 60 frames, the game starts
run(300)
shot("t2_game0")
skip_intro()
shot("t2_game1")
emit("press S 6"); run(520)                 # pause menu (needs ~450 frames to build) (CONTINUE / QUIT MYSTERY)
shot("t2_pause")
for b in "DUD":
    press(b)
emit("press S 6"); run(160)                 # QUIT MYSTERY: "NO! DONT DO IT!" item 0
shot("t2_quit")
emit("press S 6"); run(520)                 # NO: back to the pause menu
emit("press S 6"); run(300)                 # CONTINUE: back to the game
emit("press S 6"); run(520)                 # pause again
press("D"); emit("press S 6"); run(160)     # QUIT MYSTERY
press("D"); emit("press S 6"); run(500)     # YES: soft reset
shot("t2_reset")
write("tour2.txt", "# Menu tour 2 (generated by gen.py): bats, password start, pause menu, quit")

# --------------------------------------------------------------------------------------- tour 3
# Carnival (mystery 1) from the sub-menu START, pause menu, cheat code, DEBUG ROOMS / OBJECTS
run(1800)                                   # after the soft reset the logos are short: no Start needed,
shot("t3_menu")                             # the whole bat animation runs and the main menu appears
press("D", 6, 30)
shot("t3_menu1")
title_menu_item(0)                          # PLAY HA HA CARNIVAL (cursor on item 1)
emit("press S 6"); run(160)                 # START (item 0)
run(300)
skip_intro()
shot("t3_game")
emit("press S 6"); run(520)                 # pause menu (needs ~450 frames to build)
shot("t3_pause0")
cheat()
shot("t3_cheat")
emit("press S 6"); run(300)                 # CONTINUE
shot("t3_cont")
run(100)
emit("press S 6"); run(520)                 # pause again: now with ROOMS / OBJECTS
shot("t3_pause")
press("D"); press("D")
emit("press S 6"); run(250)                 # DEBUG ROOMS
shot("t3_rooms0")
for b in "DDDDDUUDDDDDDDDDDDDDDDDDDDDAUCAC":
    press(b, 6, 20)
shot("t3_rooms1")
press("D"); press("D")
emit("press B 6"); run(250)                 # pick a room -> pause menu
shot("t3_pause1")
press("D"); press("D"); press("D")
emit("press S 6"); run(250)                 # DEBUG OBJECTS
shot("t3_obj0")
for b in "DDDDDDDDDDDDDDDDDDCAUUUDD":
    press(b, 6, 20)
emit("press B 6"); run(250)                 # pick an object -> room list
shot("t3_obj1")
for b in "DDD":
    press(b, 6, 20)
emit("press B 6"); run(250)
shot("t3_obj2")
write("tour3.txt", "# Menu tour 3 (generated by gen.py): Carnival start, pause menu, DEBUG ROOMS and OBJECTS editors")
