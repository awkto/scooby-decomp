#!/usr/bin/env python3
"""Generates port/scripts/inv_items.txt: continuation of tools/scripts/story/w0_cafe_items.txt
(Cafe, inventory = Oil, Can Opener, Battery) that fills the inventory to 9 items by poking.
Pointer mode is left open.  Used by port/tools/inv_dt.sh and port/scripts/mouse/inventory.txt."""
OBJ = 0xFF1200
extra = [100, 99, 96, 92, 121, 120]      # Chili, Beads, Heater, Scissors, Pot, Pot o' Water
out = []
w = out.append
w("# generated by gen_inv_items.py -- do not edit")
w("run 60")
for i in extra:
    w("poke %X 2 1" % (OBJ + 26 * i + 6))          # object record +6 (room) = 1: carried
lst = [134, 124, 132] + extra
for k, v in enumerate(lst):
    w("poke %X 2 %X" % (0xFF0A1E + 2 * k, v))
w("poke %X 2 FFFF" % (0xFF0A1E + 2 * len(lst)))
w("run 10")
print("\n".join(out))
