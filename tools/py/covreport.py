#!/usr/bin/env python3
"""Coverage report from data/exec_starts.txt against the generated disassembly (src/scooby.s).

    covreport.py [--md OUT.md]

Instruction addresses come from an `as -aln` listing of src/scooby.s.  "Functions" are loc_ labels that are
bsr/jsr targets or dc.l pointer-table entries (entry points reached only via jmp/bra/fall-through are merged
into the preceding function).  A function is "never executed" when none of its instructions executed.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CODE_REGIONS = [(0x200, 0x11000), (0x1F6D7A, 0x1F7082)]
LINE = re.compile(r"^\s*\d+ ([0-9a-f]{4,8}) (?:[0-9A-F]{4} ?)* *\t+(.*)$")


def listing():
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    lst = os.path.join(ROOT, "build", "covreport.lst")
    subprocess.check_call(["m68k-linux-gnu-as", "-m68000", "--register-prefix-optional", "-I", os.path.join(ROOT, "build"),
                           f"-aln={lst}", "-o", os.devnull, os.path.join(ROOT, "src", "scooby.s")])
    return open(lst, errors="replace").read().split("\n")


def in_code(a):
    return any(lo <= a < hi for lo, hi in CODE_REGIONS)


def analyse():
    executed = set()
    for line in open(os.path.join(ROOT, "data", "exec_starts.txt")):
        if line.strip() and not line.startswith("#"):
            executed.add(int(line, 16))
    insns = {}
    entries = set()
    for l in listing():
        m = LINE.match(l)
        if not m:
            continue
        addr, t = int(m.group(1), 16), m.group(2).strip()
        if not t:
            continue
        tok = t.split()[0]
        if tok.startswith((".", "|")) or tok.endswith(":"):
            continue
        if tok.startswith("dc."):
            if tok == "dc.l":
                mm = re.match(r"dc\.l\s+(loc_([0-9A-F]{6}))\b", t)
                if mm:
                    entries.add(int(mm.group(2), 16))
            if not (tok == "dc.w" and "|" in t):
                continue
        if not in_code(addr):
            continue
        insns[addr] = t
        mm = re.match(r"(?:bsr|jsr)\S*\s+\(?(loc_([0-9A-F]{6}))", t)
        if mm:
            entries.add(int(mm.group(2), 16))
    return insns, entries, executed


def main():
    md = sys.argv[sys.argv.index("--md") + 1] if "--md" in sys.argv else None
    insns, entries, executed = analyse()
    addrs = sorted(insns)
    ex = [a for a in addrs if a in executed]
    stray = [a for a in executed if a not in insns and in_code(a)]
    ents = sorted(e for e in entries | {0x200} if e in insns)
    funcs = []
    for i, e in enumerate(ents):
        end = ents[i + 1] if i + 1 < len(ents) else 1 << 32
        body = [a for a in addrs if e <= a < end]
        n, hit = len(body), sum(1 for a in body if a in executed)
        funcs.append((e, n, hit, (body[-1] + 2 if body else e) - e))
    never = [f for f in funcs if f[2] == 0]
    partial = [f for f in funcs if 0 < f[2] < f[1]]
    full = [f for f in funcs if f[2] == f[1]]
    lines = []
    out = lines.append
    out("# Runtime coverage report")
    out("")
    out("Generated by `tools/py/covreport.py` from `data/exec_starts.txt` (merged harness coverage, see `tools/py/mergecov.py`)")
    out("and the instruction list of `src/scooby.s`.")
    out("")
    out(f"* instructions in the code area (`$000200-$010FFF`, `$1F6D7A-$1F7081`): {len(addrs)}")
    out(f"* executed at least once: {len(ex)} ({100.0 * len(ex) / len(addrs):.1f} %)")
    out(f"* executed starts not in the disassembly (RAM-code / data misparsed): {len(stray)}")
    out(f"* functions (bsr/jsr targets + pointer-table entries): {len(funcs)}; fully covered {len(full)}, partially {len(partial)}, never executed {len(never)}")
    out("")
    out("## Never-executed functions")
    out("")
    out("| entry | instructions | bytes |")
    out("|---|---|---|")
    for e, n, h, size in never:
        out(f"| `loc_{e:06X}` | {n} | {size} |")
    out("")
    out("## Partially covered functions (lowest coverage first, top 60)")
    out("")
    out("| entry | executed / total |")
    out("|---|---|")
    for e, n, h, size in sorted(partial, key=lambda f: f[2] / f[1])[:60]:
        out(f"| `loc_{e:06X}` | {h} / {n} |")
    text = "\n".join(lines) + "\n"
    if md:
        open(md, "w").write(text)
    print("\n".join(lines[:9]))


if __name__ == "__main__":
    main()
