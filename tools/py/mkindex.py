#!/usr/bin/env python3
"""Generate the per-room route scripts (tools/scripts/rooms/) and the room index (states/INDEX.md).

    mkindex.py [--ok-file runs/states/index.json]

Each tools/scripts/rooms/w<mystery>_r<NN>.txt is self-contained: boot, title menu, CONTINUE, type the password
for that room (state = the world's initial game-state block, i.e. what a fresh game has), skip the intro, and
`save room_w<m>_r<NN>`.  Running it with the harness regenerates the (gitignored) savestate.
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gfx  # noqa: E402
import password  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
VARIANT = "init"


def init_state(rom, world):
    hdr = struct.unpack(">I", rom[0x31AF2 + 4 * world:0x31AF2 + 4 * world + 4])[0]
    s0 = struct.unpack(">I", rom[hdr:hdr + 4])[0]
    return bytes(rom[s0:s0 + 29])


def main():
    okf = sys.argv[sys.argv.index("--ok-file") + 1] if "--ok-file" in sys.argv else None
    ok = json.load(open(okf)) if okf and os.path.exists(okf) else {}
    rom = gfx.rom()
    boot = [l.rstrip("\n") for l in open(os.path.join(ROOT, "tools/scripts/boot_title.txt"))
            if l.strip() and not l.startswith("#") and not l.startswith("save")]
    os.makedirs(os.path.join(ROOT, "tools/scripts/rooms"), exist_ok=True)
    rows = []
    for w in (0, 1):
        world = gfx.World(w)
        st = init_state(rom, w)
        for r in range(2, 2 + world.nrooms):
            room = world.room(r)
            pw = password.encode(r, st)
            name = f"w{w}_r{r:02d}"
            lines = [f"# Reaches room {r} '{room.name}' of mystery {w} ({'Blake' + chr(39) + 's Hotel' if w == 0 else 'Ha Ha Carnival'})",
                     f"# via the CONTINUE password screen; password {pw} (start room {r}, initial game state)",
                     f"# generated by tools/py/mkindex.py; ends with `save room_{name}`"]
            lines += boot
            lines += password.full_script(w, r, st)
            lines.append(f"save room_{name}")
            open(os.path.join(ROOT, f"tools/scripts/rooms/{name}.txt"), "w").write("\n".join(lines) + "\n")
            res = ok.get(f"pw_w{w}_r{r}_{VARIANT}", {}).get("ok")
            rows.append((w, r, room.name, f"{room.map_w}x{room.map_h}", pw, name, res))
    os.makedirs(os.path.join(ROOT, "states"), exist_ok=True)
    with open(os.path.join(ROOT, "states/INDEX.md"), "w") as f:
        f.write("# Savestate route index\n\n")
        f.write("Savestates themselves are **not** committed (`states/*.state` and `runs/` are gitignored; they are\n"
                "ROM-derived). Every state is regenerated by a deterministic harness script:\n\n"
                "    tools/harness/h.sh tools/scripts/rooms/w0_r16.txt runs/out    # needs build/harness (see README)\n\n"
                "then use `runs/out/room_w0_r16.state` with `load room_w0_r16` (copy the file into the run dir).\n"
                "On the VMs: `tools/py/vmjob.sh warp` builds all of them under `runs/states/` in about a minute.\n\n"
                "Rooms are reached through the game's own **password screen** (title -> PLAY ... -> CONTINUE), see\n"
                "`docs/passwords.md` for the password format. The state is the world's initial game-state block, so these\n"
                "are fresh-game states placed at each room. `Verified` = after the script `$FF06AA/$FF06AC` held the\n"
                "expected mystery/room.\n\n")
        f.write("| mystery | room | name | map | script | password | verified |\n|---|---|---|---|---|---|---|\n")
        for w, r, nm, mp, pw, name, res in rows:
            f.write(f"| {w} | {r} | {nm} | {mp} | `tools/scripts/rooms/{name}.txt` | `{pw}` | "
                    f"{'yes' if res else ('NO' if res is False else '?')} |\n")
    print(len(rows), "room scripts written")


if __name__ == "__main__":
    main()
